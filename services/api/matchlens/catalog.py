#: How a match's event stream was obtained. The distinction matters because a
#: hand-authored excerpt that uses the provider's event schema is not a
#: provider payload and must never be presented as one.
ProvenanceKind = Literal["synthetic", "provider_payload", "provider_schema_excerpt"]


class MatchMetadata(BaseModel):
    model_config = ConfigDict(extra="forbid")

    match_id: str
    label: str
    competition: str
    season: str
    #: The round the match was played in, as declared by the provider. The
    #: library groups matches by it, so an unannotated fixture reports None
    #: rather than being folded into a round it never belonged to.
    stage: Optional[str] = None
    match_date: Optional[str] = None
    home_team: str
    away_team: str
    home_score: Optional[int] = None
    away_score: Optional[int] = None
    coverage_level: DataCoverageLevel
    data_provider: str  # "synthetic" | "statsbomb_open_data"
    description: str
    license_ref: str
    attribution_text: Optional[str] = None
    events_count: Optional[int] = None
    format_seconds: Optional[int] = None
    capabilities: list[str] = Field(default_factory=list)
    home_provider_team_id: Optional[str] = None
    away_provider_team_id: Optional[str] = None
    continuous_coverage: bool = False
    completeness_status: Optional[str] = None
    completeness: Optional[dict[str, Any]] = None
    source_declared_complete: Optional[bool] = None
    official_score_note: Optional[str] = None
    #: Provider index score compared against the goals recorded in the event
    #: stream. A disagreement is reported, never merged into a single number.
    score_reconciliation: Optional[dict[str, Any]] = None
    #: How the event stream was obtained. Defaults to the provider kind for
    #: provider matches and to ``synthetic`` for generated scenarios.
    provenance_kind: ProvenanceKind = "provider_payload"
    #: The upstream provider match this entry is derived from, when the entry
    #: is an excerpt rather than the full payload.
    provider_match_id: Optional[str] = None
    #: Three-state data availability contract. A catalogued match may be shown
    #: before its payload is installed; only an analysis-ready match may enter
    #: a replay or investigation session.
    availability_status: Optional[str] = None
    dataset_installed: bool = False
    analysis_ready: bool = False
    availability_reason: Optional[str] = None
    install_hint: Optional[str] = None
    verification_basis: Optional[str] = None
    dataset_sha256: Optional[str] = None
    dataset_path: Optional[str] = None
    availability: Optional[dict[str, Any]] = None


class MatchCatalog:
    """Central registry of available matches across synthetic and real data providers."""

    @classmethod
    def _synthetic_match(cls, key: str) -> MatchMetadata:
        sc = SCENARIOS[key]
        return MatchMetadata(
            match_id=f"syn_{key}",
            label=sc["label"],
            competition="MatchLens Simulation League",
            season="2025/2026",
            stage="scenario",
            match_date="2026-03-15",
            home_team=TEAMS["H"],
            away_team=TEAMS["N"],
            home_score=1 if key in ("default", "transitions", "balanced") else (2 if key == "comeback" else 0),
            away_score=1 if key in ("counterattack", "transitions", "balanced", "comeback") else 0,
            coverage_level=DataCoverageLevel.C0_SYNTHETIC,
            data_provider="synthetic",
            description=sc["description"],
            license_ref="MatchLens Proprietary Synthetic Engine (MIT)",
            attribution_text="Generated by MatchLens Synthetic Event Generator",
            events_count=180,
            format_seconds=cls.SYNTHETIC_DURATION_SECONDS,
            source_declared_complete=True,
            provenance_kind="synthetic",
            capabilities=[
                "full_match_simulation",
                "oaai_dynamics",
                "spatial_drilldown",
                "whatif_simulation",
                "multi_perspective_stories",
                "gate_verification",
            ],
        )

    @classmethod
    def list_matches(cls) -> list[MatchMetadata]:
        matches: list[MatchMetadata] = []

        # 1. Synthetic C0 Scenarios
        for key in SCENARIOS:
            matches.append(cls._synthetic_match(key))

        # 2. Provider matches declared by the committed source manifest. The
        # manifest carries metadata only; the payloads live outside version
        # control because the provider agreement forbids redistribution.
        matches.extend(cls._manifest_matches())

        # 3. MatchLens-authored dataset fixtures bundled with the package.
        if MATCHES_DIR.exists():
            for p in sorted(MATCHES_DIR.glob("*.json")):
                try:
                    with open(p, "r", encoding="utf-8") as f:
                        data = json.load(f)
                    meta = data.get("metadata")
                    if meta:
                        meta = dict(meta)
                        # A bundled fixture that uses the provider's event schema
                        # is an excerpt, not the provider payload. It must never
                        # default to being read as a full provider match.
                        meta.setdefault(
                            "provenance_kind",
                            "synthetic"
                            if meta.get("data_provider") == "synthetic"
                            else "provider_schema_excerpt",
                        )
                        matches.append(MatchMetadata(**meta))
                except Exception:
                    pass

        # Completeness is verified from events, never copied from a declared final time.
        return [cls._with_availability(cls._with_completeness(m)) for m in matches]

    @classmethod
    def get_match(cls, match_id: str) -> Optional[MatchMetadata]:
        """Resolve one match without rebuilding the whole 80-match catalog."""
        if match_id.startswith("syn_"):
            key = match_id.removeprefix("syn_")
            if key not in SCENARIOS:
                return None
            return cls._with_availability(cls._with_completeness(cls._synthetic_match(key)))

        entry = cls.manifest_entries().get(match_id)
        if entry is not None:
            meta = cls._metadata_from_manifest_entry(match_id, entry)
            if meta is None:
                return None
            return cls._with_availability(cls._with_completeness(meta))

        candidate = MATCHES_DIR / f"{match_id}.json" if cls._safe_match_id(match_id) else None
        if candidate is None or not candidate.exists():
            return None
        try:
            with open(candidate, "r", encoding="utf-8") as handle:
                meta_raw = json.load(handle).get("metadata")
            if not meta_raw:
                return None
            meta_raw = dict(meta_raw)
            meta_raw.setdefault(
                "provenance_kind",
                "synthetic" if meta_raw.get("data_provider") == "synthetic" else "provider_schema_excerpt",
            )
            return cls._with_availability(cls._with_completeness(MatchMetadata(**meta_raw)))
        except Exception:
            return None

    # Alias for convenience
    get_match_meta = get_match

    # --- source manifest -------------------------------------------------------
    _manifest_cache: dict[str, Any] = {}
    _entries_cache: dict[Any, dict[str, dict[str, Any]]] = {}
    _resolved_path_cache: dict[tuple[str, str], Optional[Path]] = {}
    _dataset_path_cache: dict[tuple[Any, str], Optional[Path]] = {}

    @classmethod
    def source_manifest(cls) -> dict[str, Any]:
        """Committed provenance index. Metadata only: no provider payload."""
        try:
            stat = SOURCE_MANIFEST_PATH.stat()
        except OSError:
            return {}
        key = f"{SOURCE_MANIFEST_PATH}:{stat.st_mtime_ns}:{stat.st_size}"
        cached = cls._manifest_cache.get("__key__")
        if cached == key:
            return cls._manifest_cache["__data__"]
        try:
            data = json.loads(SOURCE_MANIFEST_PATH.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            return {}
        if not isinstance(data, dict):
            return {}
        cls._manifest_cache["__key__"] = key
        cls._manifest_cache["__data__"] = data
        return data

    @classmethod
    def manifest_entries(cls) -> dict[str, dict[str, Any]]:
        # source_manifest() re-stats the file, so a manifest edited in place,
        # or a test that redirects SOURCE_MANIFEST_PATH, cannot leave a stale
        # entry index behind. Parsing is still cached by (path, mtime, size).
        entries = cls.source_manifest().get("matches") or []
        cache_key = cls._manifest_cache.get("__key__")
        if cache_key is not None and cache_key in cls._entries_cache:
            return cls._entries_cache[cache_key]
        index = {
            str(e["match_id"]): e
            for e in entries
            if isinstance(e, dict) and e.get("match_id")
        }
        if cache_key is not None:
            if len(cls._entries_cache) > 4:
                cls._entries_cache.clear()
            cls._entries_cache[cache_key] = index
        return index

    @classmethod
    def _metadata_from_manifest_entry(
        cls, match_id: str, entry: dict[str, Any]
    ) -> Optional[MatchMetadata]:
        meta = dict(entry.get("metadata") or {})
        meta.setdefault("match_id", match_id)
        if not meta.get("match_id"):
            return None
        # The manifest keeps one completeness report per match. The metadata
        # reads it back from there instead of carrying a second copy.
        if meta.get("completeness") is None and entry.get("completeness") is not None:
            meta["completeness"] = entry["completeness"]
        # The round the match was played in lives on the manifest entry. It
        # is copied into the metadata so the library can group by it.
        if meta.get("stage") is None and entry.get("stage"):
            meta["stage"] = entry["stage"]
        try:
            return MatchMetadata(**meta)
        except Exception as exc:
            cls._manifest_rejections.append({
                "match_id": match_id,
                "error": f"{type(exc).__name__}: {exc}",
            })
            return None

    @classmethod
    def _manifest_matches(cls) -> list[MatchMetadata]:
        out: list[MatchMetadata] = []
        cls._manifest_rejections = []
        for match_id, entry in sorted(cls.manifest_entries().items()):
            meta = cls._metadata_from_manifest_entry(match_id, entry)
            if meta is not None:
                out.append(meta)
        return out

    @classmethod
    def manifest_rejections(cls) -> list[dict[str, Any]]:
        """Manifest entries the catalog could not read."""
        return list(getattr(cls, "_manifest_rejections", []))

    @staticmethod
    def _safe_match_id(match_id: str) -> bool:
        return bool(match_id) and not any(token in match_id for token in ("/", "\\", "..", "\x00"))

    @staticmethod
    def resolve_manifest_path(relative: Optional[str]) -> Optional[Path]:
        """Resolve a manifest path without trusting its platform or contents.

        Committed manifests written on Windows used backslashes. Converting the
        separators before resolution makes the same manifest usable on Linux,
        and containment prevents an absolute or ``..`` path from escaping the
        repository.
        """
        if not relative:
            return None
        raw = str(relative).replace("\\", "/").strip()
        if not raw:
            return None
        pure = PurePosixPath(raw)
        if pure.is_absolute() or ".." in pure.parts:
            return None
        if pure.parts and (":" in pure.parts[0] or pure.parts[0] in ("", ".")):
            return None
        cache_key = (str(REPO_ROOT), raw)
        if cache_key in MatchCatalog._resolved_path_cache:
            return MatchCatalog._resolved_path_cache[cache_key]
        root = REPO_ROOT.resolve()
        candidate = (root / Path(*pure.parts)).resolve()
        try:
            candidate.relative_to(root)
        except ValueError:
            candidate = None
        if len(MatchCatalog._resolved_path_cache) > 256:
            MatchCatalog._resolved_path_cache.clear()
        MatchCatalog._resolved_path_cache[cache_key] = candidate
        return candidate

    @classmethod
    def dataset_path(cls, match_id: str) -> Optional[Path]:
        """Resolve a match to its dataset file, manifest first then fixtures."""
        entry = cls.manifest_entries().get(match_id)
        if entry:
            cache_key = (cls._manifest_cache.get("__key__"), match_id)
            if cache_key not in cls._dataset_path_cache:
                cls._dataset_path_cache[cache_key] = cls.resolve_manifest_path(entry.get("dataset_path"))
            candidate = cls._dataset_path_cache[cache_key]
            return candidate if candidate is not None and candidate.exists() else None
        if not cls._safe_match_id(match_id):
            return None
        candidate = MATCHES_DIR / f"{match_id}.json"
        return candidate if candidate.exists() else None

    @classmethod
    def dataset_missing_reason(cls, match_id: str) -> Optional[str]:
        """Why a declared match cannot be served, or None when it is available."""
        entry = cls.manifest_entries().get(match_id)
        if not entry:
            return None
        if cls.dataset_path(match_id) is not None:
            return None
        declared = entry.get("dataset_path")
        if declared and cls.resolve_manifest_path(declared) is None:
            return f"dataset_path_invalid: {declared!r} is not a repo-relative path"
        return (
            "dataset_not_imported: provider payloads are excluded from version control; "
            "run scripts/ingest_statsbomb_corpus.py to materialise them"
        )

    @staticmethod
    def content_revision_from_events(
        *,
        match_id: str,
        provider: str,
        events: list[NormalizedEvent],
        home_provider_team_id: str | None = None,
        away_provider_team_id: str | None = None,
        schema_version: str = "normalized-event-v2",
        adapter_version: str = "statsbomb-adapter-v2",
        metric_version: str = "football-v2",
        model_version: str = "oaai-1.0.0",
        coverage: str = "unknown",
    ) -> tuple[str, str]:
        """Content-addressed dataset identity.

        Unlike mtime/size, this changes when an event's team, timestamp,
        coordinates, action, outcome or possession identity changes while its
        event ID stays the same.
        """
        canonical_events = []
        for event in events:
            canonical_events.append({
                "event_id": event.event_id,
                "period": event.period,
                "clock": round(float(event.clock_seconds), 4),
                "team": event.team_id,
                "provider_team": event.provider_team_id,
                "action": event.action_type.value if hasattr(event.action_type, "value") else str(event.action_type),
                "outcome": event.outcome,
                "player": event.player_id,
                "possession": event.possession_id,
                "x": event.x,
                "y": event.y,
                "end_x": event.end_x,
                "end_y": event.end_y,
                "own_goal": event.is_own_goal,
                "shootout": event.is_shootout,
            })
        content_sha = hashlib.sha256(
            json.dumps(canonical_events, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode("utf-8")
        ).hexdigest()
        revision = hashlib.sha256(json.dumps({
            "match_id": match_id,
            "provider": provider,
            "content_sha256": content_sha,
            "home_provider_team_id": home_provider_team_id,
            "away_provider_team_id": away_provider_team_id,
            "schema_version": schema_version,
            "adapter_version": adapter_version,
            "metric_version": metric_version,
            "model_version": model_version,
            "coverage": coverage,
            "event_count": len(events),
        }, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode("utf-8")).hexdigest()
        return revision, content_sha

    _dataset_revision_cache: dict[tuple[Any, ...], dict[str, Any]] = {}

    @classmethod
    def dataset_revision(cls, match_id: str) -> dict[str, Any]:
        # The revision is content-addressed, so the memo is keyed by the
        # dataset file's content digest (provider matches) or by the scenario
        # id (synthetic matches, whose generated events are deterministic).
        # A signature weaker than content — e.g. event ids — would serve a
        # stale revision after an in-place content edit with a preserved id.
        if match_id.startswith("syn_"):
            cache_key: tuple[Any, ...] = (match_id, "synthetic")
            events = cls.load_normalized_events(match_id)
        else:
            digest, events = cls._load_dataset(match_id)
            cache_key = (match_id, digest)
        cached = cls._dataset_revision_cache.get(cache_key)
        if cached is not None:
            return cached
        meta = cls.get_match(match_id)
        coverage = meta.coverage_level.value if meta else "unknown"
        revision, content_sha = cls.content_revision_from_events(
            match_id=match_id,
            provider=meta.data_provider if meta else "unknown",
            events=events,
            home_provider_team_id=meta.home_provider_team_id if meta else None,
            away_provider_team_id=meta.away_provider_team_id if meta else None,
            adapter_version=(
                "synthetic-adapter-v2" if match_id.startswith("syn_") else "statsbomb-adapter-v2"
            ),
            coverage=coverage,
        )
        result = {
            "match_id": match_id,
            "revision": revision,
            "content_sha256": content_sha,
            "event_count": len(events),
            "coverage": coverage,
            "schema_version": "normalized-event-v2",
            "adapter_version": "synthetic-adapter-v2" if match_id.startswith("syn_") else "statsbomb-adapter-v2",
            "metric_version": "football-v2",
            "model_version": "oaai-1.0.0",
        }
        cls._dataset_revision_cache[cache_key] = result
        return result

    @classmethod
    def data_version(cls, match_id: str) -> str:
        """Content revision, not mtime/size. See content_revision_from_events."""
        return str(cls.dataset_revision(match_id)["revision"])

    SYNTHETIC_DURATION_SECONDS = 720
    _completeness_cache: dict[tuple[Any, ...], DatasetCompleteness] = {}
    _event_cache: dict[tuple[Any, ...], list[NormalizedEvent]] = {}

    @classmethod
    def _disk_metadata(cls, match_id: str) -> Optional[MatchMetadata]:
        """Read one dataset's metadata row without going through list_matches()."""
        entry = cls.manifest_entries().get(match_id)
        if entry:
            meta = dict(entry.get("metadata") or {})
            meta.setdefault("match_id", match_id)
            try:
                return MatchMetadata(**meta)
            except Exception:
                return None
        path = MATCHES_DIR / f"{match_id}.json"
        if not path.exists():
            return None
        try:
            with open(path, "r", encoding="utf-8") as f:
                meta = json.load(f).get("metadata")
            return MatchMetadata(**meta) if meta else None
        except Exception:
            return None

    @classmethod
    def _completeness_cache_key(cls, match_id: str) -> tuple[Any, ...]:
        """Cache identity: synthetic fixtures are deterministic, files are content-stamped."""
        if match_id.startswith("syn_"):
            return (match_id, "synthetic")
        path = cls.dataset_path(match_id)
        if path is None:
            return (match_id, "missing")
        try:
            stat = path.stat()
            return (match_id, str(path), int(stat.st_mtime_ns), int(stat.st_size))
        except OSError:
            return (match_id, "missing")

    @classmethod
    def completeness_report(
        cls, match_id: str, events: Optional[list[NormalizedEvent]] = None
    ) -> DatasetCompleteness:
        """Single source of truth for dataset completeness.

        Shared by the hub listing and the match context so the two can never
        disagree, and re-verified whenever the underlying content changes.
        """
        digest: Optional[str] = None
        if match_id.startswith("syn_"):
            cache_key: tuple[Any, ...] = (match_id, "synthetic")
        else:
            path = cls.dataset_path(match_id)
            if path is None:
                cache_key = (match_id, "missing")
            else:
                digest = cls._dataset_digest(path)
                cache_key = (match_id, digest)
        cached = cls._completeness_cache.get(cache_key)
        if cached is not None and events is None:
            return cached

        if events is None:
            events = cls.load_normalized_events(match_id)
        synthetic = match_id.startswith("syn_")
        meta = None if synthetic else cls._disk_metadata(match_id)
        duration = float(cls.SYNTHETIC_DURATION_SECONDS if synthetic else (meta.format_seconds if meta else None) or 5400)
        raw_count = len(events) if (synthetic or meta is None) else int(meta.events_count or len(events))
        report = verify_dataset_completeness(
            events,
            raw_event_count=max(raw_count, len(events)),
            expected_duration=duration,
            source_declaration="MatchLens synthetic generator" if synthetic else (meta.data_provider if meta else "unknown"),
            synthetic=synthetic,
            declared_complete=True if synthetic else (meta.source_declared_complete if meta else None),
            conversion_drop_count=max(0, raw_count - len(events)),
            drop_reasons=(["conversion_dropped_events"] if raw_count > len(events) else []),
        )
        cls._completeness_cache[cache_key] = report
        return report

    @classmethod
    def _with_completeness(cls, meta: MatchMetadata) -> MatchMetadata:
        entry = cls.manifest_entries().get(meta.match_id)
        if entry is not None:
            # The manifest stores the report computed from the events at import
            # time, bound to the dataset checksum. Re-deriving it here would
            # force every provider match to be parsed on every catalog read.
            stored = entry.get("completeness")
            if isinstance(stored, dict) and stored.get("status"):
                status = str(stored.get("status"))
                return meta.model_copy(
                    update={
                        "completeness_status": status,
                        "completeness": stored,
                        "continuous_coverage": bool(stored.get("full_match_allowed"))
                        or status == "COMPLETE_VERIFIED",
                    }
                )
            return meta.model_copy(
                update={
                    "completeness_status": "DATASET_NOT_IMPORTED",
                    "continuous_coverage": False,
                }
            )
        try:
            report = cls.completeness_report(meta.match_id)
        except Exception:
            return meta
        return meta.model_copy(
            update={
                "completeness_status": report.status,
                "completeness": report.model_dump(),
                "continuous_coverage": report.full_match_allowed,
            }
        )

    @classmethod
    def _with_availability(cls, meta: MatchMetadata) -> MatchMetadata:
        """Attach the CATALOGUED → MATERIALIZED → ANALYSIS_READY contract.

        Listing must stay cheap for the full corpus, so the status is derived
        from the committed import receipt and file existence. The content hash
        is re-verified at session entry and on every dataset load; a tampered
        payload therefore fails closed instead of being analysed.
        """
        if meta.match_id.startswith("syn_"):
            availability = synthetic_availability(meta.match_id)
        else:
            entry = cls.manifest_entries().get(meta.match_id)
            path = cls.dataset_path(meta.match_id)
            # Never expose the server's absolute filesystem path in an API
            # payload; the committed manifest path is already repo-relative.
            display_path = (
                str(entry.get("dataset_path") or "").replace("\\", "/")
                if entry is not None and path is not None
                else None
            )
            if entry is not None:
                status = meta.completeness_status
                availability = manifest_availability(
                    meta.match_id,
                    dataset_path=display_path,
                    declared_sha256=entry.get("dataset_sha256"),
                    completeness_status=status,
                    completeness=meta.completeness,
                    provider_mapping_ok=bool(
                        meta.home_provider_team_id
                        and meta.away_provider_team_id
                        and meta.home_provider_team_id != meta.away_provider_team_id
                    ),
                    events_count=meta.events_count,
                )
            elif path is not None:
                checksum_verified = True
                try:
                    checksum_verified = bool(cls._dataset_digest(path))
                except OSError:
                    checksum_verified = False
                try:
                    fixture_path = path.resolve().relative_to(REPO_ROOT.resolve()).as_posix()
                except ValueError:
                    fixture_path = path.name
                availability = fixture_availability(
                    meta.match_id,
                    dataset_path=fixture_path,
                    completeness_status=meta.completeness_status,
                    completeness=meta.completeness,
                    events_count=meta.events_count,
                    checksum_verified=checksum_verified,
                )
            else:
                availability = missing_provider_dataset(meta.match_id)

        return meta.model_copy(
            update={
                "availability_status": availability.status,
                "dataset_installed": availability.dataset_installed,
                "analysis_ready": availability.analysis_ready,
                "availability_reason": availability.reason,
                "install_hint": availability.install_hint,
                "verification_basis": availability.verification_basis,
                "dataset_sha256": availability.declared_sha256,
                "dataset_path": availability.dataset_path,
                "availability": availability.model_dump(),
            }
        )

    @classmethod
    def availability(cls, match_id: str) -> Optional[MatchAvailability]:
        """Availability for one match without exposing the whole catalog model."""
        meta = cls.get_match(match_id)
        if meta is None:
            return None
        if meta.availability:
            return MatchAvailability.model_validate(meta.availability)
        return None

    @classmethod
    def verify_analysis_ready(cls, match_id: str) -> tuple[bool, str | None]:
        """Live verification before a session is allowed to switch matches.

        This is deliberately stricter than the listing: it hashes the file
        against the manifest, parses the payload and requires at least one
        normalized event. A missing or tampered file is reported, never
        replaced by synthetic data.
        """
        availability = cls.availability(match_id)
        if availability is None:
            return False, "match_not_found"
        if not availability.analysis_ready:
            return False, availability.reason or "match_not_analysis_ready"
        if match_id.startswith("syn_"):
            return True, None
        try:
            events = cls.load_normalized_events(match_id)
        except FileNotFoundError as exc:
            return False, f"dataset_not_imported: {exc}"
        except ValueError as exc:
            return False, f"dataset_integrity_error: {exc}"
        if not events:
            return False, "dataset_has_no_events"
        return True, None

    @classmethod
    def get_match_context(cls, match_id: str) -> MatchContext:
        meta = cls.get_match(match_id)
        if not meta:
            raise FileNotFoundError(f"Match not found: {match_id}")

        revision_info = cls.dataset_revision(match_id)
        events = cls.load_normalized_events(match_id)

        if match_id.startswith("syn_"):
            mode = "synthetic_replay"
            home_id, away_id = "H", "N"
            declared_duration = cls.SYNTHETIC_DURATION_SECONDS
            clock = build_match_clock(
                events, nominal_duration=declared_duration, synthetic=True
            )
            duration = int(round(clock["nominal_duration"]))
            observed_end = clock["observed_end"]
            period = clock["period"]
            partial_notice = None
            frame = "fixed"
            home_provider = away_provider = None
            completeness = cls.completeness_report(match_id, events)
        else:
            mode = "partial_fixture" if meta.coverage_level == DataCoverageLevel.C1_PARTIAL else "historical"
            # Explicit provider identity only. Name-substring inference is forbidden.
            home_provider = meta.home_provider_team_id
            away_provider = meta.away_provider_team_id
            if not home_provider or not away_provider or home_provider == away_provider:
                raise ValueError(
                    f"missing_provider_team_mapping: {match_id}; metadata must declare "
                    "home_provider_team_id and away_provider_team_id"
                )
            home_id, away_id = "H", "N"
            declared_duration = meta.format_seconds or 5400
            clock = build_match_clock(
                events, nominal_duration=declared_duration, synthetic=False
            )
            # The declared provider format may reserve 600 seconds for a
            # shoot-out. duration is playing time; shootout_clock is separate.
            duration = int(round(clock["nominal_duration"]))
            observed_end = clock["observed_end"]
            period = clock["period"]
            frame = "team_relative"
            completeness = cls.completeness_report(match_id, events)
            if completeness.status == "INVALID_CORRUPTED":
                raise ValueError(f"invalid_dataset_completeness: {match_id}")

        continuous = completeness.status == "COMPLETE_VERIFIED"
        partial_notice = (
            None if continuous else
            f"Partial fixture: {completeness.status.lower()} with "
            f"{completeness.normalized_event_count} events, observed through "
            f"{(completeness.observed_end or observed_end):.0f}s of a nominal {duration}s match. "
            "Unobserved intervals are Unknown, not zero and not continuous possession."
        )

        return MatchContext(
            match_id=meta.match_id,
            provider=meta.data_provider,
            data_coverage=meta.coverage_level.value,
            mode=mode,
            home_team_id=home_id,
            home_team_name=meta.home_team,
            away_team_id=away_id,
            away_team_name=meta.away_team,
            home_score=meta.home_score if meta.home_score is not None else 0,
            away_score=meta.away_score if meta.away_score is not None else 0,
            match_clock_basis="match_elapsed",
            duration=duration,
            observed_end=observed_end,
            replayable_end=clock["replayable_end"],
            nominal_duration=clock["nominal_duration"],
            stoppage_time=clock["stoppage_time_seconds"],
            as_of=clock["as_of"],
            periods=clock["periods"],
            shootout_clock=clock["shootout_clock"],
            clock_version=clock["clock_version"],
            period=period,
            attack_directions=(
                {"H": "left_to_right", "N": "right_to_left"}
                if frame == "fixed" else {"H": "left_to_right", "N": "left_to_right"}
            ),
            event_source=meta.license_ref,
            capabilities=meta.capabilities,
            data_version=revision_info["revision"],
            partial_notice=partial_notice,
            competition=meta.competition,
            season=meta.season,
            label=meta.label,
            dataset_revision=revision_info["revision"],
            content_sha256=revision_info["content_sha256"],
            schema_version="normalized-event-v2",
            adapter_version="synthetic-adapter-v2" if match_id.startswith("syn_") else "statsbomb-adapter-v2",
            metric_version="football-v2",
            model_version="oaai-1.0.0",
            home_provider_team_id=home_provider,
            away_provider_team_id=away_provider,
            coordinate_frame=frame,
            continuous_coverage=continuous,
            completeness_status=completeness.status,
            completeness=completeness.model_dump(),
            coverage_verified=completeness.verified,
            event_count=len(events),
            score_basis="observed_prefix",
            official_home_score=meta.home_score,
            official_away_score=meta.away_score,
            provenance_kind=meta.provenance_kind,
        )

    _dataset_digest_cache: dict[tuple[Any, ...], str] = {}

    @classmethod
    def _dataset_digest(cls, path: Path) -> str:
        """Content hash of the dataset file. Identity is content, never mtime.

        The hash itself is memoized per (path, mtime, size): re-reading a
        multi-megabyte payload on every completeness lookup made every catalog
        read pay the full digest cost even when nothing changed.
        """
        try:
            stat = path.stat()
            cache_key = (str(path), stat.st_mtime_ns, stat.st_size)
        except OSError:
            cache_key = None
        if cache_key is not None:
            cached = cls._dataset_digest_cache.get(cache_key)
            if cached is not None:
                return cached
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        if cache_key is not None:
            cls._dataset_digest_cache[cache_key] = digest
        return digest

    @classmethod
    def _load_dataset(cls, match_id: str) -> tuple[str, list[NormalizedEvent]]:
        """Return (content digest, normalized events) for one provider match.

        The digest is the dataset's identity, so the normalized-event cache is
        keyed by content: editing a payload changes its digest even when the
        file's mtime and size are preserved.
        """
        file_path = cls.dataset_path(match_id)
        if file_path is None:
            reason = cls.dataset_missing_reason(match_id) or f"Match data file not found: {match_id}"
            raise FileNotFoundError(reason)

        raw_bytes = file_path.read_bytes()
        digest = hashlib.sha256(raw_bytes).hexdigest()

        entry = cls.manifest_entries().get(match_id) or {}
        expected_sha = entry.get("dataset_sha256")
        if expected_sha and digest != expected_sha:
            raise ValueError(
                f"dataset_checksum_mismatch: {match_id} "
                f"expected={expected_sha[:16]} actual={digest[:16]}"
            )

        cached = cls._event_cache.get(digest)
        if cached is not None:
            return digest, cached

        data = json.loads(raw_bytes.decode("utf-8"))
        meta_raw = data.get("metadata") or {}
        home_pid = meta_raw.get("home_provider_team_id")
        away_pid = meta_raw.get("away_provider_team_id")
        if not home_pid or not away_pid or str(home_pid) == str(away_pid):
            raise ValueError(f"missing_provider_team_mapping: {match_id}")
        raw_events = data.get("events")
        if not isinstance(raw_events, list):
            raise ValueError(f"malformed_event_payload: {match_id}")
        adapter = StatsBombAdapter(match_id=match_id)
        events = adapter.load_events(raw_events)
        mapping = {str(home_pid): "H", str(away_pid): "N"}
        canonical: list[NormalizedEvent] = []
        for e in events:
            if e.team_id not in mapping:
                raise ValueError(f"unmapped_provider_team: {match_id}:{e.team_id}")
            canonical.append(e.model_copy(update={"team_id": mapping[e.team_id]}))
        cls._event_cache[digest] = canonical
        return digest, canonical

    @classmethod
    def load_normalized_events(cls, match_id: str) -> list[NormalizedEvent]:
        """Loads and converts events for the specified match_id into NormalizedEvent list."""
        if match_id.startswith("syn_"):
            scenario_key = match_id.replace("syn_", "", 1)
            raw_events = generate_match(scenario=scenario_key)
            return cls._convert_synthetic_events(raw_events, match_id)
        return cls._load_dataset(match_id)[1]

    @classmethod
    def load_multiple_matches(
        cls, match_ids: list[str], *, allow_partial: bool = False
    ) -> dict[str, list[NormalizedEvent]]:
        """Batch load matches without collapsing failures into empty event lists."""
        results, errors = cls.load_multiple_matches_with_status(match_ids)
        failures = {mid: st for mid, st in errors.items() if st["status"] != "ok"}
        if failures and not allow_partial:
            detail = ", ".join(f"{mid}={st['status']}" for mid, st in failures.items())
            raise ValueError(f"batch_load_failed: {detail}")
        return results

    @classmethod
    def load_multiple_matches_with_status(
        cls, match_ids: list[str]
    ) -> tuple[dict[str, list[NormalizedEvent]], dict[str, dict]]:
        """Distinguish missing / parse_error / unsupported / zero-events / ok."""
        results: dict[str, list[NormalizedEvent]] = {}
        status: dict[str, dict] = {}
        for m_id in match_ids:
            meta = cls.get_match(m_id)
            if meta is None:
                # A file may exist but be unreadable. Distinguish that from a
                # genuinely absent source instead of reporting both as missing.
                candidate = cls.dataset_path(m_id)
                if candidate is not None:
                    try:
                        payload = json.loads(candidate.read_text(encoding="utf-8"))
                        meta_raw = payload.get("metadata")
                        if not isinstance(meta_raw, dict):
                            raise ValueError("metadata_missing")
                        MatchMetadata(**meta_raw)
                    except Exception as exc:
                        status[m_id] = {"status": "parse_error", "event_count": 0, "reason": str(exc)}
                        continue
                status[m_id] = {"status": "missing", "event_count": 0, "reason": "not_in_catalog"}
                continue
            if meta.data_provider != "statsbomb_open_data" and not m_id.startswith("syn_"):
                status[m_id] = {"status": "unsupported", "event_count": 0, "reason": meta.data_provider}
                continue
            try:
                events = cls.load_normalized_events(m_id)
            except FileNotFoundError as exc:
                status[m_id] = {"status": "missing", "event_count": 0, "reason": str(exc)}
                continue
            except Exception as exc:  # malformed provider payload
                status[m_id] = {"status": "parse_error", "event_count": 0, "reason": str(exc)}
                continue
            if not events:
                status[m_id] = {"status": "zero_events", "event_count": 0, "reason": "source_loaded_but_empty"}
            else:
                status[m_id] = {
                    "status": "ok",
                    "event_count": len(events),
                    "coverage": meta.coverage_level.value,
                }
            results[m_id] = events
        return results, status

    @classmethod
    def get_batch_summary(cls, match_ids: list[str]) -> dict[str, Any]:
        """Return comparable, coverage-aware cross-match statistics.

        Raw totals are reported but never presented as equivalent per-match
        rates: partial fixtures and complete synthetic matches are marked as
        non-comparable unless their coverage and model versions align.
        """
        batch_events, load_status = cls.load_multiple_matches_with_status(match_ids)
        per_match: dict[str, dict] = {}
        coverage_flags: set[str] = set()
        for mid, evs in batch_events.items():
            meta = cls.get_match(mid)
            ctx = cls.get_match_context(mid) if meta else None
            passes = sum(1 for ev in evs if ev.action_type == ActionType.PASS)
            carries = sum(1 for ev in evs if ev.action_type == ActionType.CARRY)
            shots = [ev for ev in evs if ev.action_type == ActionType.SHOT]
            goals = sum(1 for ev in shots if ev.outcome in ("goal", "own_goal_for"))
            home_goals = sum(1 for ev in shots if ev.team_id == "H" and ev.outcome == "goal") + sum(
                1 for ev in shots if ev.team_id == "N" and ev.outcome == "own_goal_for"
            )
            away_goals = sum(1 for ev in shots if ev.team_id == "N" and ev.outcome == "goal") + sum(
                1 for ev in shots if ev.team_id == "H" and ev.outcome == "own_goal_for"
            )
            duration = ctx.duration if ctx else 0
            coverage = meta.coverage_level.value if meta else "unknown"
            coverage_flags.add(coverage)
            continuous = bool(ctx.continuous_coverage) if ctx else False
            observed = float(ctx.observed_end) if ctx else 0.0
            per_match[mid] = {
                "match_id": mid,
                "match_date": meta.match_date if meta else None,
                "competition": meta.competition if meta else None,
                "home_team": meta.home_team if meta else None,
                "away_team": meta.away_team if meta else None,
                "home_team_id": (ctx.home_provider_team_id or ctx.home_team_id) if ctx else None,
                "away_team_id": (ctx.away_provider_team_id or ctx.away_team_id) if ctx else None,
                "provider": ctx.provider if ctx else None,
                "coverage": coverage,
                "continuous_coverage": continuous,
                "sample_size_events": len(evs),
                "observed_end": observed or None,
                "duration_seconds": duration,
                "event_coverage": "unknown" if not continuous else "complete",
                "passes": passes,
                "carries": carries,
                "shots": len(shots),
                "goals": goals,
                "home_goals": home_goals,
                "away_goals": away_goals,
                # Standardized rates only where the denominator is known and
                # coverage is continuous; otherwise explicitly withheld.
                "passes_per_90": round(passes * 5400 / duration, 2) if ctx and continuous and duration else None,
                "shots_per_90": round(len(shots) * 5400 / duration, 2) if ctx and continuous and duration else None,
                "carries_per_90": round(carries * 5400 / duration, 2) if ctx and continuous and duration else None,
                "events_per_minute_observed": round(len(evs) / (observed / 60), 2) if observed else None,
                "load_status": load_status.get(mid, {}).get("status"),
                "rate_status": "comparable" if ctx and continuous else "withheld_partial_coverage",
            }

        comparable = bool(per_match) and (
            len({p["coverage"] for p in per_match.values()}) == 1
            and all(p["continuous_coverage"] for p in per_match.values())
            and len({p["duration_seconds"] for p in per_match.values()}) == 1
        )

        team_summaries: dict[str, dict] = {}
        for mid, p in per_match.items():
            for side in ("home_team", "away_team"):
                team = p.get(side)
                if not team:
                    continue
                summary = team_summaries.setdefault(team, {
                    "team": team,
                    "matches": [],
                    "continuous_matches": 0,
                    "partial_matches": 0,
                    "goals_total": 0,
                    "per_90_available": [],
                })
                summary["matches"].append(mid)
                summary.setdefault("team_ids", set()).add(
                    p["home_team_id"] if side == "home_team" else p["away_team_id"]
                )
                summary["goals_total"] += p["home_goals"] if side == "home_team" else p["away_goals"]
                if p["continuous_coverage"]:
                    summary["continuous_matches"] += 1
                    summary["per_90_available"].append({
                        "match_id": mid,
                        "shots_per_90": p["shots_per_90"],
                        "passes_per_90": p["passes_per_90"],
                    })
                else:
                    summary["partial_matches"] += 1

        for summary in team_summaries.values():
            summary["team_ids"] = sorted(str(x) for x in summary.get("team_ids", set()) if x)

        trend = sorted(
            (
                {
                    "match_id": mid,
                    "match_date": p["match_date"],
                    "coverage": p["coverage"],
                    "rate_status": p["rate_status"],
                    "shots_per_90": p["shots_per_90"],
                    "passes_per_90": p["passes_per_90"],
                    "goals": p["goals"],
                }
                for mid, p in per_match.items()
            ),
            key=lambda row: row["match_date"] or "",
        )
        warnings: list[str] = []
        if not comparable:
            warnings.append("mixed_coverage_or_duration: per-90 comparison withheld")
        for mid, status in load_status.items():
            if status["status"] != "ok":
                warnings.append(f"{mid}:{status['status']}")

        return {
            "match_ids": match_ids,
            "sample_selection_note": (
                "The curated corpus is a functional-acceptance sample, not an unbiased "
                "population of football matches. Cross-match rates describe these selected "
                "matches and carry the competition/season selection bias."
            ),
            "total_matches": len(batch_events),
            "total_events": sum(p["sample_size_events"] for p in per_match.values()),
            "passes_count": sum(p["passes"] for p in per_match.values()),
            "carries_count": sum(p["carries"] for p in per_match.values()),
            "shots_count": sum(p["shots"] for p in per_match.values()),
            "goals_count": sum(p["goals"] for p in per_match.values()),
            "per_match": per_match,
            "team_summaries": team_summaries,
            "trend": trend,
            "load_status": load_status,
            "coverage_mix": sorted(coverage_flags),
            "metric_version": "football-v2",
            "comparable": comparable,
            "warnings": warnings,
            "comparability_note": (
                "Coverage, duration and continuous-coverage align; per-90 rates are comparable."
                if comparable else
                "Mixed or partial coverage: raw totals are reported, but per-90 comparison is withheld."
            ),
        }

    @classmethod
    def _convert_synthetic_events(cls, events: tuple, match_id: str) -> list[NormalizedEvent]:
        """Normalize internal synthetic events into the unified NormalizedEvent model."""
        normalized: list[NormalizedEvent] = []
        kind_map = {
            "pass": ActionType.PASS,
            "shot": ActionType.SHOT,
            "recovery": ActionType.RECOVERY,
            "restart": ActionType.RESTART,
            "end": ActionType.OTHER,
        }

        prev_team = None
        for ev in events:
            action_type = kind_map.get(ev.kind, ActionType.OTHER)
            outcome = ev.outcome
            possession_changed = (prev_team is not None and prev_team != ev.team)
            prev_team = ev.team

            source = RawSourceRecord(
                provider="synthetic",
                provider_event_id=ev.id,
                schema_version="1.0",
                license_ref="MatchLens Synthetic Generator",
            )

            normalized.append(
                NormalizedEvent(
                    event_id=f"{match_id}_{ev.id}",
                    match_id=match_id,
                    source=source,
                    period=1 if ev.t <= 360 else 2,
                    clock_seconds=float(ev.t),
                    clock_basis="match_elapsed",
                    team_id=ev.team,
                    attack_direction="left_to_right" if ev.team == "H" else "right_to_left",
                    possession_id=None,
                    possession_changed=possession_changed,
                    player_id=ev.actor,
                    player_name=ev.actor,
                    action_type=action_type,
                    outcome=outcome,
                    x=round(float(ev.start[0]), 2),
                    y=round(float(ev.start[1]), 2),
                    end_x=round(float(ev.end[0]), 2),
                    end_y=round(float(ev.end[1]), 2),
                )
            )

        return normalized
